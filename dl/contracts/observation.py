"""
Shared Pydantic v2 data contracts for DisasterLens observations and fusion state.

Independent of FastAPI and database frameworks.
"""

from __future__ import annotations

from datetime import UTC, datetime
from enum import Enum
from typing import Any
from uuid import uuid4

from pydantic import AliasChoices, BaseModel, Field

from dl.contracts.enums import HazardType
from dl.generator.models import Zone


class RoadStatus(str, Enum):
    """Operational backend and routing status values (uppercase contract)."""

    BLOCKED = "BLOCKED"
    PARTIAL = "PARTIAL"
    CLEAR = "CLEAR"
    UNCERTAIN = "UNCERTAIN"
    STALE = "STALE"
    UNKNOWN = "UNKNOWN"


class SegmentObservation(BaseModel):
    """
    Observation record for an individual road segment.
    """

    id: str | None = None
    observation_id: str = Field(
        default_factory=lambda: f"obs_{uuid4().hex[:8]}",
        description="Unique identifier for this observation instance",
    )
    scene_id: str | None = Field(default=None, description="Optional synthetic scene identifier")
    segment_id: str = Field(..., pattern=r"^SEG-\d{3}$", description="Road segment ID (e.g. SEG-001)")
    source: str = Field(..., description="Camera ID or contributor label, e.g. synthetic_camera_1")
    zone: Zone = Field(..., description="Geographic zone: NW, NE, SW, SE")

    # RULE: captured_at strictly governs freshness.
    # AliasChoices allows seamless ingestion of Tejash's 'capture_time' from scenario.json.
    captured_at: datetime = Field(
        ...,
        validation_alias=AliasChoices("captured_at", "capture_time"),
        description="Ground-truth capture timestamp. Sole driver of observation age and freshness.",
    )

    # RULE: uploaded_at is ingestion metadata only. Must NEVER determine freshness.
    uploaded_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="Ingestion arrival timestamp. Auditing metadata only; never affects freshness.",
    )
    analyzed_at: datetime | None = Field(
        default=None, description="Vision model execution timestamp"
    )

    verdict: RoadStatus = Field(
        ..., description="Raw or guarded observed road status: BLOCKED, PARTIAL, CLEAR, UNCERTAIN"
    )
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Model or oracle confidence score [0, 1]")
    max_coverage: float | None = Field(
        default=None, ge=0.0, le=1.0, description="Maximum road width cross-section coverage [0, 1]"
    )
    hazard_type: HazardType | None = Field(default=None, description="Identified hazard type if visible")
    blocking_hazards: list[str] = Field(default_factory=list, description="IDs of hazards covering the segment")
    evidence: str | None = Field(default=None, description="Descriptive rationale for verdict")
    visibility: str | None = Field(default="full", description="Visibility status: 'full', 'partial', 'none'")

    # Direct vs Mapped comparison
    direct_verdict: RoadStatus | None = Field(
        default=None, description="Direct verdict returned by vision model classification"
    )
    mapped_verdict: RoadStatus | None = Field(
        default=None, description="Geometric status derived from hazard bounding boxes/polygons"
    )

    # Operational flags
    near_miss: bool = Field(default=False, description="True if hazard is adjacent but does not obstruct")
    recovery: bool = Field(default=False, description="True if observation represents receded hazard verification")
    model_id: str | None = Field(default=None, description="Identifier of vision model used")
    is_mock: bool = Field(default=False, description="True if generated by mock oracle provider")
    image_path: str | None = Field(default=None, description="Server storage reference/relative path")
    original_filename: str | None = Field(default=None, description="Original filename for audit metadata")
    affected_segments: list[str] = Field(default_factory=list, description="IDs of affected road segments")
    raw_payload: dict[str, Any] | None = Field(default=None, description="Raw source payload")


class SegmentState(BaseModel):
    """
    Effective road status and metadata evaluated at query time (as_of).
    """

    segment_id: str = Field(..., pattern=r"^SEG-\d{3}$")
    status: RoadStatus = Field(..., description="Effective status: BLOCKED, PARTIAL, CLEAR, UNCERTAIN, STALE, UNKNOWN")
    freshness: str = Field(..., description="Freshness label: 'fresh', 'ageing', 'stale', 'unknown'")
    age_hours: float | None = Field(default=None, description="Elapsed hours since captured_at")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    max_coverage: float | None = Field(default=None, ge=0.0, le=1.0)
    hazard_type: HazardType | None = None
    blocking_hazards: list[str] = Field(default_factory=list)
    last_observation_id: str | None = None
    captured_at: datetime | None = None
    source: str | None = None
    is_stale_from_blocked: bool = Field(
        default=False, description="True if STALE road was originally observed as BLOCKED"
    )
    as_of: datetime = Field(..., description="Query time used to calculate this state")
    warning: str | None = Field(default=None, description="Optional advisory warning")


class AffectedSegments(BaseModel):
    """
    Report of segments whose effective condition changed after an observation ingestion.
    """

    observation_id: str
    affected_segment_ids: list[str] = Field(default_factory=list)
    previous_statuses: dict[str, RoadStatus] = Field(default_factory=dict)
    new_statuses: dict[str, RoadStatus] = Field(default_factory=dict)


class RouteAlert(BaseModel):
    """Alert raised when road status changes impact a tracked or saved route."""

    route_id: str
    alert_type: str = Field(
        ..., description="Alert code, e.g. PRIMARY_NOW_BLOCKED, ROUTE_CLEARED, ROUTE_DEGRADED"
    )
    segment_id: str
    message: str
    severity: str = Field(default="warning", description="'info', 'warning', 'critical'")


class RouteAlerts(BaseModel):
    """Collection of route alerts."""

    alerts: list[RouteAlert] = Field(default_factory=list)
